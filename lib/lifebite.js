// 把「每份 ±N 分钟」按年频次折算并格式化；返回 {minutes, text, sign}
function projection(minutesPerServing, timesPerYear) {
  const total = Math.round(minutesPerServing * timesPerYear);
  const abs = Math.abs(total);
  let text;
  if (abs >= 1440) text = (abs / 1440).toFixed(1) + ' 天';
  else if (abs >= 60) text = (abs / 60).toFixed(1) + ' 小时';
  else text = abs + ' 分钟';
  return {minutes: total, text: (total >= 0 ? '+' : '-') + text, sign: total >= 0 ? 'good' : 'bad'};
}

// 汇总多份食物：返回总分钟数与好坏计数
function summarize(ids) {
  let minutes = 0, good = 0, bad = 0, count = 0;
  (ids || []).forEach((id) => {
    const f = findFood(id);
    if (!f) return;
    minutes += f.life;
    count++;
    if (f.life >= 0) good++; else bad++;
  });
  return {minutes, good, bad, count, tone: minutes >= 0 ? 'good' : 'bad'};
}

// 分数 → 展示语义（供 UI 上色）
function toneOf(life) {
  return life >= 0 ? 'good' : 'bad';
}

function signed(n) {
  return (n >= 0 ? '+' : '') + n;
}

return {STORAGE_KEY, FOODS, findFood, projection, summarize, toneOf, signed};
